int main()
{
    static_assert(sizeof(kEvo4) == 470, "captured length");
    Uac2Playback p{};
    assert(Uac2ParsePlayback(kEvo4, sizeof(kEvo4), 16, p));
    assert(p.controlInterface == 0 && p.streamInterface == 1 && p.alternate == 2);
    assert(p.clockId == 41 && p.terminalId == 2 && p.featureId == 10 && p.featureChannels == 4);
    assert(p.featureVolumeMask == 0x1e);
    assert(p.channels == 4 && p.subslot == 2 && p.bits == 16);
    assert(p.dataEp == 0x01 && p.dataMaxPacket == 104 && p.dataInterval == 1);
    assert(p.feedbackEp == 0x81 && p.feedbackMaxPacket == 4 && p.feedbackInterval == 4);
    Uac2Playback p24{};
    assert(Uac2ParsePlayback(kEvo4, sizeof(kEvo4), 24, p24) && p24.alternate == 1 && p24.subslot == 4 && p24.dataMaxPacket == 208);
    Uac2Playback none{};
    assert(!Uac2ParsePlayback(kEvo4, sizeof(kEvo4), 32, none));
    assert(!Uac2ParsePlayback(kEvo4, 100, 16, none)); // truncated: no streaming interface
    // Capture (interface 2) and DFU (interface 3) never match playback.
    assert(p.streamInterface != 2 && p.streamInterface != 3);

    // Pacing: 48 kHz at 8000 microframes/s is exactly 6 frames.
    Uac2FeedbackPacer pacer;
    pacer.Start(48000, 8000, 104 / 8);
    assert(pacer.nominal == 6u << 16);
    for (int i = 0; i < 100; ++i) assert(pacer.Next() == 6);
    // 44.1 kHz: 5.5125 frames; over 8000 packets exactly 44100 frames.
    pacer.Start(44100, 8000, 13);
    uint32_t total = 0;
    for (int i = 0; i < 8000; ++i) { const uint32_t n = pacer.Next(); assert(n == 5 || n == 6); total += n; }
    assert(total == 44100);
    // Feedback: device 0.1 % fast, in 16.16; then 10.14-justified and garbage.
    pacer.Start(48000, 8000, 13);
    const uint32_t fast = (6u << 16) + 393;
    assert(pacer.Feed(fast, 4) && pacer.current == fast);
    total = 0; for (int i = 0; i < 8000; ++i) total += pacer.Next();
    assert(total >= 48047 && total <= 48048);
    assert(pacer.Feed((6u << 14) + 10, 4) && pacer.current == (6u << 16) + 40); // 10.14 -> <<2
    assert(!pacer.Feed(0, 4) && !pacer.Feed(0x7fffffff, 4) && pacer.current == (6u << 16) + 40);
    assert(pacer.Feed(6u << 14, 3) && pacer.current == 6u << 16); // full-speed 3-byte 10.14
    pacer.Start(48000, 8000, 5); assert(pacer.Next() == 5); // clamped to max packet

    // Isochronous TRB and endpoint context words.
    assert(XhciIsochControl(true, true, true) == (1u | 4u | 32u | (5u << 10) | (1u << 31)));
    assert(XhciIsochControl(false, false, false, 0x123) == (4u | (5u << 10) | (0x123u << 20)));
    assert(XhciIsochStatus(48) == 48);
    const auto out = XhciIsochContext(false, 1, 104, 48);
    assert(out.dw0 == 0 && out.dw1 == ((1u << 3) | (104u << 16)) && out.dw4 == (48u | (104u << 16)));
    const auto fb = XhciIsochContext(true, 4, 4, 4);
    assert(fb.dw0 == (3u << 16) && fb.dw1 == ((5u << 3) | (4u << 16)) && fb.dw4 == (4u | (4u << 16)));
    const auto mult = XhciIsochContext(false, 1, 0x1000 | 512, 512);
    assert(((mult.dw1 >> 8) & 3) == 2 && (mult.dw4 >> 16) == 1536);

    // Volume clamp in 1/256 dB.
    assert(Uac2VolumeQ8(-40, int16_t(0x8100), 0) == int16_t(-10240));
    assert(Uac2VolumeQ8(-200, int16_t(0x8100), 0) == int16_t(0x8100));
    assert(Uac2VolumeQ8(10, int16_t(0x8100), 0) == 0);

    // Sine: quarter points and accuracy against a few reference values.
    assert(Uac2SineQ15(0) == 0 && Uac2SineQ15(0x80000000u) == 0);
    assert(Uac2SineQ15(0x40000000u) >= 32700 && Uac2SineQ15(0xC0000000u) <= -32700);
    const int32_t s30 = Uac2SineQ15(0x15555555u); // 30 degrees: 16384
    assert(s30 > 16384 - 100 && s30 < 16384 + 100);
    // Tone: 1 s of 440 Hz at 48 kHz with 10 ms fades, peak within amplitude.
    Uac2Tone tone; tone.Start(440, 48000, 48000, 480, 8192);
    int16_t first = tone.NextSample(); assert(first == 0);
    int peak = 0, crossings = 0; int16_t prev = first; uint32_t n = 1;
    while (tone.Active()) { const int16_t v = tone.NextSample(); ++n; if ((v < 0) != (prev < 0)) ++crossings; prev = v; if (v > peak) peak = v; if (-v > peak) peak = -v; }
    assert(n == 48000 && peak <= 8192 && peak > 8100 && prev == 0);
    assert(crossings >= 878 && crossings <= 882); // 440 cycles, two crossings each
    assert(tone.NextSample() == 0);
    std::puts("usb uac2: PASS");
}
