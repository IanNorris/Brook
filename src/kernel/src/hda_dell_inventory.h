inline bool HdaDellToneInventoryMatches() {
    constexpr unsigned count=sizeof(HdaDellPciReferenceEntries)/sizeof(HdaDellPciReferenceEntries[0]);
    if(PciBootInventoryCount()!=count || PciBootInventorySeen()!=count)return false;
    for(const auto& expected:HdaDellPciReferenceEntries) {
        unsigned matches=0;
        for(unsigned i=0;i<count;++i) {
            PciBootEntry e{};if(!PciBootInventoryRead(i,&e))return false;const auto& d=e.device;
            if(d.bus!=expected.bus || d.dev!=expected.dev || d.fn!=expected.fn)continue;
            ++matches;if(d.vendorId!=expected.vendor || d.deviceId!=expected.device || d.classCode!=expected.cls ||
                d.subclass!=expected.sub || d.progIf!=expected.prog || (e.headerType&127)!=expected.header)return false;
            for(unsigned b=0;b<6;++b)if(d.bar[b]!=expected.bars[b])return false;
        }
        if(matches!=1)return false;
    }
    return true;
}
