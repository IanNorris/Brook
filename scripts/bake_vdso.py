#!/usr/bin/env python3
"""Validate and embed the self-contained two-page x86-64 vDSO ELF.

Only the code page is embedded. The kernel supplies the clock page separately;
ELF section/symbol tables beyond the load segment must never reach that page.
"""
import argparse
from pathlib import Path
import struct


def code_page(blob):
    def require(condition, message):
        if not condition:
            raise ValueError(message)

    require(len(blob) >= 64, "truncated ELF")
    header = struct.unpack_from("<16sHHIQQQIHHHHHH", blob)
    ident, kind, machine, version, entry, phoff = header[:6]
    require(ident[:7] == b"\x7fELF\x02\x01\x01" and kind == 3
            and machine == 62 and version == 1, "expected x86-64 little-endian ET_DYN")
    require(header[8:11] == (64, 56, 3), "unexpected ELF/program headers")
    require(phoff == 64 and phoff + 3 * 56 <= len(blob), "invalid program headers")
    ph = [struct.unpack_from("<IIQQQQQQ", blob, phoff + i * 56) for i in range(3)]
    loads = [p for p in ph if p[0] == 1]
    require(len(loads) == 1, "expected one PT_LOAD for glibc vDSO base discovery")
    code = loads[0]
    require(code[1:4] == (5, 0, 0) and code[6] == 8192
            and phoff + 3 * 56 <= code[5] <= 4096 and code[5] <= len(blob)
            and code[7] == 4096 and entry < code[5], "invalid executable code page")
    dynamic = [p for p in ph if p[0] == 2]
    require(len(dynamic) == 1, "missing dynamic header")
    dyn = dynamic[0]
    require(dyn[1] == 4 and dyn[2] == dyn[3] and dyn[5] == dyn[6]
            and dyn[2] + dyn[5] <= code[5] and dyn[5] % 16 == 0,
            "invalid dynamic segment")
    require(any(p[0] == 0x6474e551 and p[1] == 6 for p in ph), "invalid stack flags")
    tags = {}
    terminated = False
    for offset in range(dyn[2], dyn[2] + dyn[5], 16):
        tag, value = struct.unpack_from("<QQ", blob, offset)
        if not tag:
            terminated = True
            break
        require(tag not in tags, "duplicate dynamic tag")
        tags[tag] = value
    require(terminated, "unterminated dynamic table")
    # Explicit allowlist excludes dependencies, relocation tables, PLT, TLS
    # descriptors, constructors and other loader side effects.
    require(set(tags) <= {14, 30, 4, 5, 6, 10, 11, 0x6ffffef5,
                          0x6ffffff0, 0x6ffffffc, 0x6ffffffd}, "unsupported dynamic tag")
    require({4, 5, 6, 10, 11, 0x6ffffef5, 0x6ffffff0,
             0x6ffffffc, 0x6ffffffd} <= set(tags), "missing lookup/version tables")
    require(tags[11] == 24 and tags[0x6ffffffd] == 2, "invalid symbol/version layout")
    for tag in (4, 5, 6, 0x6ffffef5, 0x6ffffff0, 0x6ffffffc):
        require(0 < tags[tag] < code[5], "lookup table outside code page")
    require(tags[5] + tags[10] <= code[5], "string table outside code page")
    page = bytearray(4096)
    page[:code[5]] = blob[:code[5]]
    # Dynamic linking uses program headers and DT_* tables, never section headers.
    page[40:48] = bytes(8)  # e_shoff
    page[58:64] = bytes(6)  # e_shentsize, e_shnum, e_shstrndx
    return bytes(page)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("--image", type=Path)
    parser.add_argument("--cpp", type=Path)
    args = parser.parse_args()
    if not args.image and not args.cpp:
        parser.error("at least one of --image or --cpp is required")
    page = code_page(args.input.read_bytes())
    if args.image:
        args.image.write_bytes(page)
    if args.cpp:
        rows = [", ".join(f"0x{x:02x}" for x in page[i:i+16]) for i in range(0, 4096, 16)]
        args.cpp.write_text("// Generated by bake_vdso.py; do not edit.\n"
                            "#include <stdint.h>\nnamespace brook {\n"
                            "extern const uint8_t g_vdsoCodePage[4096] = {\n"
                            + ",\n".join(rows) + "\n};\n}\n")


if __name__ == "__main__":
    main()
