#!/usr/bin/env python3
"""Turn the nix/nak-m4-kernel.nix output into src/kernel/src/nv_gsp/nak_m4_kernel.h.

The header carries the NAK-encoded SM75 kernel and the QMD NAK filled for it, with the
provenance (Mesa version, source store path, sha256 of each blob). `--check` regenerates
into memory and fails if the checked-in header differs.

    python3 scripts/nak_m4_header.py $(nix-build --no-out-link nix/nak-m4-kernel.nix) [--check]
"""
import argparse
import hashlib
import pathlib
import struct
import sys

HEADER = pathlib.Path(__file__).resolve().parent.parent / 'src/kernel/src/nv_gsp/nak_m4_kernel.h'


def words(blob: bytes) -> list[int]:
    if len(blob) % 4:
        raise SystemExit('blob is not a whole number of words')
    return list(struct.unpack(f'<{len(blob) // 4}I', blob))


def table(name: str, ws: list[int]) -> str:
    rows = [', '.join(f'0x{w:08x}' for w in ws[i:i + 6]) for i in range(0, len(ws), 6)]
    return f'inline constexpr uint32_t {name}[{len(ws)}] = {{\n    ' + ',\n    '.join(rows) + ',\n};\n'


def render(out: pathlib.Path) -> str:
    code = (out / 'kernel.bin').read_bytes()
    qmd = (out / 'qmd.bin').read_bytes()
    info = dict(line.split(' ', 1) for line in (out / 'info.txt').read_text().splitlines() if ' ' in line)
    prov = (out / 'PROVENANCE').read_text().strip().splitlines()
    asm = (out / 'kernel.asm').read_text().rstrip().splitlines()
    local = int(info['local_size'].split()[0])
    lines = [
        '// GENERATED by scripts/nak_m4_header.py from nix/nak-m4-kernel.nix. Do not edit.',
        '// SPDX-License-Identifier: MIT',
        '//',
    ] + ['// ' + l.strip() for l in prov] + [
        '//',
        f'// kernel.bin sha256 {hashlib.sha256(code).hexdigest()}',
        f'// qmd.bin    sha256 {hashlib.sha256(qmd).hexdigest()}',
        '//',
        '// NAK info: ' + ', '.join(f'{k} {v}' for k, v in info.items()),
        '//',
        '// NAK assembly:',
    ] + ['//   ' + l for l in asm] + [
        '#pragma once',
        '#include <stdint.h>',
        '',
        'namespace brook::nvgsp::nak_m4 {',
        '',
        table('kCode', words(code)),
        table('kQmd', words(qmd)),
        f'inline constexpr uint64_t kShaderVa = {info["shader_va"]}ull;',
        f'inline constexpr uint64_t kCb0Va = {info["cb0_va"].split()[0]}ull;',
        f'inline constexpr uint32_t kInvocations = {int(info["invocations"])};',
        f'inline constexpr uint32_t kLocalSize = {local};',
        f'inline constexpr uint32_t kStoreValue = {info["store"]}u;',
        f'inline constexpr uint32_t kNumGprs = {int(info["num_gprs"])};',
        '',
        '}  // namespace brook::nvgsp::nak_m4',
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('out', type=pathlib.Path)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = render(a.out)
    if a.check:
        if HEADER.read_text() != text:
            print(f'{HEADER} differs from {a.out}', file=sys.stderr)
            return 1
        print('nak_m4_kernel.h matches')
        return 0
    HEADER.write_text(text)
    print(f'wrote {HEADER}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
