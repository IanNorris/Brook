#!/usr/bin/env python3
"""Generate and validate a SteamRT provider cache from installed Nix exports.

Run in the guest. This does not modify the exports, library symlinks or /etc.
Publish the resulting cache as /etc/ld.so.cache separately during provisioning.
The optional copied loader uses that same cache location; its installed Nix
source is unchanged, and exact source/output hashes describe the adaptation.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path
import subprocess


def relocate_loader_cache(data, original, destination='/etc/ld.so.cache'):
    """Adapt only the standalone cache literal in a copied ELF64 loader.

    Nix's loader otherwise ignores the cache regenerated by SteamRT. Never
    modify the installed store output, executable code, ELF layout or the
    separate occurrence embedded in help text. The build ID stays unchanged;
    the manifest's content hashes identify this modified compatibility copy.
    """
    old, new = original.encode('ascii'), destination.encode('ascii')
    if (not original.startswith('/nix/store/') or not original.endswith('/etc/ld.so.cache')
            or destination != '/etc/ld.so.cache' or len(new) > len(old)):
        raise ValueError('Unsupported loader cache relocation')
    if len(data) < 64 or data[:7] != b'\x7fELF\x02\x01\x01':
        raise ValueError('Expected little-endian ELF64 loader')
    header = struct.unpack_from('<16sHHIQQQIHHHHHH', data)
    if header[1] != 3 or header[2] != 62 or header[8] != 64 or header[9] != 56:
        raise ValueError('Unsupported loader ELF layout')
    phoff, phnum = header[5], header[10]
    if not phnum or phoff + phnum * 56 > len(data):
        raise ValueError('Invalid loader program headers')
    matches = []
    start = 0
    while True:
        start = data.find(old + b'\0', start)
        if start < 0:
            break
        if start > 0 and data[start - 1] == 0:
            matches.append(start)
        start += 1
    if len(matches) != 1:
        raise ValueError('Expected one standalone loader cache literal')
    offset = matches[0]
    end = offset + len(old) + 1
    covered = False
    for i in range(phnum):
        kind, flags, at, _, _, filesz, memsz, _ = struct.unpack_from('<IIQQQQQQ', data, phoff + i * 56)
        if at + filesz > len(data) or memsz < filesz:
            raise ValueError('Invalid loader segment bounds')
        if kind == 1 and at < end and offset < at + filesz:
            if flags != 4:
                raise ValueError('Cache literal must be in read-only, non-executable data')
            if at <= offset and end <= at + filesz:
                covered = True
    if not covered:
        raise ValueError('Cache literal is not load-backed')
    result = data[:offset] + new + bytes(end - offset - len(new)) + data[end:]
    assert len(result) == len(data) and result[:offset] == data[:offset] and result[end:] == data[end:]
    return result, dict(offset=offset, original=original, destination=destination,
                        span_bytes=end-offset, source_sha256=hashlib.sha256(data).hexdigest(),
                        output_sha256=hashlib.sha256(result).hexdigest(), build_id_unchanged=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ldconfig', type=Path, required=True)
    parser.add_argument('--exports', type=Path, required=True)
    parser.add_argument('--include-directory', type=Path, action='append', default=[])
    parser.add_argument('--loader', type=Path,
                        help='Also package the matching installed x86-64 host loader')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    tool = args.ldconfig.resolve(strict=True)
    directories = set()
    libraries = {}
    for export in sorted(args.exports.iterdir()):
        if '.so' not in export.name:
            continue
        target = export.resolve(strict=True)
        if not target.is_relative_to('/nix/store') or not target.is_file():
            raise RuntimeError(f'Export is not an installed Nix library: {export}')
        with target.open('rb') as stream:
            if stream.read(4) != b'\x7fELF':
                continue
        libraries[str(export)] = str(target)
        directories.add(target.parent)
    for directory in args.include_directory:
        directory = directory.resolve(strict=True)
        if not directory.is_relative_to('/nix/store') or not directory.is_dir():
            raise RuntimeError(f'Unapproved library directory: {directory}')
        directories.add(directory)
    if not directories:
        raise RuntimeError('No installed provider libraries')
    # An approved package can export another closure member through a symlink
    # (for example gcc's libgcc_s). Include its installed canonical directory.
    pending = list(directories)
    while pending:
        for entry in pending.pop().iterdir():
            if '.so' not in entry.name:
                continue
            target = entry.resolve(strict=True)
            if not target.is_file():
                continue
            if not target.is_relative_to('/nix/store'):
                raise RuntimeError(f'Provider library escapes Nix store: {entry}')
            with target.open('rb') as stream:
                is_elf = stream.read(4) == b'\x7fELF'
            if is_elf and target.parent not in directories:
                directories.add(target.parent)
                pending.append(target.parent)
    args.output.mkdir(parents=True, exist_ok=False)
    config = args.output / 'ld.so.conf'
    cache = args.output / 'ld.so.cache'
    config.write_text(''.join(str(p) + '\n' for p in sorted(directories)))
    command = [str(tool), '-X', '-i', '-C', str(cache), '-f', str(config)]
    with (args.output / 'stdout.log').open('wb') as stdout, (args.output / 'stderr.log').open('wb') as stderr:
        result = subprocess.run(command, stdout=stdout, stderr=stderr)
    if result.returncode:
        raise RuntimeError(f'ldconfig exited {result.returncode}; see {args.output}')
    listing = subprocess.run([str(tool), '-p', '-C', str(cache)], capture_output=True, check=True)
    (args.output / 'cache-list.txt').write_bytes(listing.stdout)
    targets = {}
    for line in listing.stdout.decode().splitlines():
        if ' => ' not in line:
            continue
        label, filename = line.strip().split(' => ', 1)
        path = Path(filename)
        target = path.resolve(strict=True)
        if not target.is_file() or not any(target.is_relative_to(directory) for directory in directories):
            raise RuntimeError(f'Cache target outside installed manifest: {path} -> {target}')
        targets[label] = str(target)
    if not targets:
        raise RuntimeError('Generated cache is empty')
    manifest = dict(command=command, tool=str(tool),
                    tool_sha256=hashlib.sha256(tool.read_bytes()).hexdigest(),
                    exports=libraries, directories=sorted(map(str, directories)),
                    targets=targets, cache=str(cache),
                    cache_sha256=hashlib.sha256(cache.read_bytes()).hexdigest())
    manifest['config_sha256'] = hashlib.sha256(config.read_bytes()).hexdigest()
    if args.loader:
        loader = args.loader.resolve(strict=True)
        data = loader.read_bytes()
        if (not loader.is_relative_to('/nix/store') or data[:6] != b'\x7fELF\x02\x01'
                or data[18:20] != b'\x3e\x00'):
            raise RuntimeError('Expected an installed x86-64 ELF host loader')
        libc = (loader.parent / 'libc.so.6').resolve(strict=True)
        if str(libc) not in targets.values():
            raise RuntimeError('Loader libc is absent from the validated provider cache')
        data, relocation = relocate_loader_cache(data, str(loader.parent.parent / 'etc/ld.so.cache'))
        (args.output / 'ld-linux-x86-64.so.2').write_bytes(data)
        manifest['loader'] = dict(source=str(loader), libc=str(libc),
                                  sha256=hashlib.sha256(data).hexdigest(),
                                  cache_relocation=relocation)
    (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(dict(cache=str(cache), cache_sha256=manifest['cache_sha256'],
                          directories=len(directories), libraries=len(targets), validated=True)))


if __name__ == '__main__':
    main()
