import assert from 'node:assert/strict';
import {createMonitorPty} from '../dist/runtime/monitor-pty.js';
const encoder=new TextEncoder(),decoder=new TextDecoder();
const logs=[],messages=[],timers=[];
const monitor=createMonitorPty({enabled:true,print:text=>logs.push(text),onMessage:entry=>messages.push(entry),schedule:(callback,delay)=>{const timer={callback,delay};timers.push(timer);return timer;},unschedule:()=>{}});
let notifications=0;
const subscription=monitor.pty.onReadable(()=>notifications++);
const greeting=JSON.stringify({QMP:{version:{qemu:{major:8,minor:2,micro:0}},capabilities:[]}})+'\r\n';
monitor.pty.write(encoder.encode(greeting.slice(0,15)));
assert.equal(monitor.pty.readable,false,'Partial JSON must not trigger negotiation');
monitor.pty.write(encoder.encode(greeting.slice(15)));
await Promise.resolve();
assert.equal(notifications,1);
assert.equal(monitor.diagnostics.greeting,true);
const partial=monitor.pty.read(7),rest=monitor.pty.read(4096);
const command=JSON.parse(decoder.decode(Uint8Array.from([...partial,...rest])));
assert.equal(command.execute,'qmp_capabilities');
assert.equal(monitor.pty.readable,false);
monitor.pty.write(encoder.encode('{"return":{},"id":"brook-capabilities"}\n'));
assert.deepEqual(timers.map(timer=>timer.delay),[5000,20000,60000]);
assert.equal(monitor.diagnostics.capabilities,true);
timers[0].callback();
const commands=decoder.decode(monitor.pty.read(4096)).trim().split('\n').map(line=>JSON.parse(line));
assert.deepEqual(commands.map(command=>command.execute),['query-status','human-monitor-command','query-blockstats']);
assert.equal(commands[1].arguments['command-line'],'info registers');
monitor.pty.write(encoder.encode('{"return":"RIP=0000000000001234","id":"registers-5s"}\n'));
assert.equal(messages.at(-1).message.return,'RIP=0000000000001234');
monitor.pty.write(encoder.encode('A non-JSON diagnostic warning\n'));
assert.deepEqual(logs,['A non-JSON diagnostic warning']);
subscription.dispose();
await Promise.resolve();
const before=notifications;
monitor.send('query-status');
await Promise.resolve();
assert.equal(notifications,before,'Disposed listeners must stay disconnected');
monitor.dispose();
assert.equal(monitor.send('query-status'),false);
assert.equal(monitor.pty.readable,false);
// Reproduce bytes arriving before Emscripten registers its wait callback.
const raced=createMonitorPty({enabled:true,print:()=>{},schedule:()=>0,unschedule:()=>{}});
raced.send('query-status');
await Promise.resolve();
let recovered=0;
const racedSubscription=raced.pty.onReadable(()=>recovered++);
await Promise.resolve();
assert.equal(recovered,1,'A late subscriber must observe already-queued bytes');
assert(raced.diagnostics.transport.pendingBytes>0);
raced.pty.read(4096);
assert.equal(raced.diagnostics.transport.pendingBytes,0);
assert(raced.diagnostics.transport.bytesRead>0);
racedSubscription.dispose();
raced.dispose();
const cancelled=createMonitorPty({enabled:true,print:()=>{},schedule:()=>0,unschedule:()=>{}});
cancelled.send('query-status');
await Promise.resolve();
let cancelledNotifications=0;
const cancelledSubscription=cancelled.pty.onReadable(()=>cancelledNotifications++);
cancelledSubscription.dispose();
await Promise.resolve();
assert.equal(cancelledNotifications,0,'Disposal must cancel a queued late-subscriber notification');
cancelled.dispose();
const oobTimers=[];
const oob=createMonitorPty({enabled:true,oob:true,print:()=>{},schedule:(callback,delay)=>{oobTimers.push({callback,delay});return 0;},unschedule:()=>{}});
oob.pty.write(encoder.encode('{"QMP":{"capabilities":["oob"]}}\n'));
const capabilities=JSON.parse(decoder.decode(oob.pty.read(4096)));
assert.deepEqual(capabilities.arguments,{enable:['oob']});
oob.pty.write(encoder.encode('{"return":{},"id":"brook-capabilities"}\n'));
assert.equal(oob.diagnostics.oobEnabled,true);
oobTimers[0].callback();
const oobCommands=decoder.decode(oob.pty.read(4096)).trim().split('\n').map(JSON.parse);
assert.equal(oobCommands[0]['exec-oob'],'query-yank');
assert.equal(oobCommands[1].execute,'query-status');
oobTimers[1].callback();
const laterCommands=decoder.decode(oob.pty.read(4096)).trim().split('\n').map(JSON.parse);
assert.equal(laterCommands.find(command=>command.id==='pc-bytes-20s').arguments['command-line'],'x/80bx $pc-16');
assert(!oobCommands.some(command=>command.id?.startsWith('pc-bytes')),'PC bytes are captured only at20/60seconds');
oob.dispose();
const output=[];
const plain=createMonitorPty({print:text=>output.push(text)});
plain.pty.write(encoder.encode('normal stderr\n'));
assert.deepEqual(output,['normal stderr']);
assert.equal(plain.send('query-status'),false);
plain.dispose();
console.log('Monitor PTY checks passed: fragmented negotiation, queue events/partial reads, timed VM queries, response parsing, late-subscriber readiness, transport metrics, OOB capability/probes, listener disposal, disabled mode.');
